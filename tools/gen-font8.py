def row_byte(s):
    b = 0
    for c in range(8):
        if c < len(s) and s[c] == '#':
            b |= 0x80 >> c
    return b

def main():
    out = []
    out.append("// examples/snes/font8.h — GENERATED by tools/gen-font8.py. Do not edit by hand.")
    out.append("// 8x8 2bpp font, ASCII 0x20..0x5F; tile# = ch - 0x20. Word = row bitmap (plane 0), plane 1 = 0.")
    out.append("#ifndef FONT8_H")
    out.append("#define FONT8_H")
    out.append("#include <stdint.h>")
    out.append("#define FONT8_FIRST 0x20")
    out.append("#define FONT8_N 64")
    out.append("static const uint16_t FONT8[FONT8_N * 8] = {")
    for code in range(0x20, 0x60):
        ch = chr(code)
        art = G.get(ch, ["........"] * 8)
        words = ", ".join("0x%04X" % row_byte(art[r]) for r in range(8))
        label = ch if ch != " " else "spc"
        out.append("  %s,  // 0x%02X '%s'" % (words, code, label))
    out.append("};")
    out.append("#endif /* FONT8_H */")
    sys.stdout.write("\n".join(out) + "\n")

if __name__ == "__main__":
    main()
