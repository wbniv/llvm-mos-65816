// --- pacing --------------------------------------------------------------
// MEASURED on target (bsnes-jg, SlowROM 2.68 MHz), not estimated. Isolating the
// cost with -DSEAMDEMO_NO_DRAW / -DSEAMDEMO_NO_HUD showed drawing is ~5.6x the
// VM and the HUD is free. For the SHIPPING payload:
//
//   VM alone, no drawing .......... 52   ops/frame  (-DSEAMDEMO_NO_DRAW)
//   shipping build ................ 5.69 ops/frame
//   act length .................... ~2,050 frames = ~34 s
//                                   (bisected: act1_laps is 0 at frame 2,000,
//                                    1 at frame 2,100)
//
// Drawing does NOT scale linearly with segment count -- the canvas dirty-tile
// flush is budgeted at CANVAS_FLUSH_TILES per v-blank, so past some density it is
// a throughput wall, not a per-line cost. Don't fit a two-parameter model here;
// measure the payload you are shipping.
//
// The FIRST cut of the P0 payload (256-byte chapters, MOVE 2 times in 9) came to
// 65,961 ops / 12,729 segments = a ~245 s act against the plan's 20-30 s. That is
// not tunable from this file -- op count and MOVE density are the generator's --
// so P0 was regenerated against these measurements: 48-byte chapters and one MOVE
// slot per instruction menu give 10,494 ops / 367 segments.
//
// OPS_PER_FRAME is matched to the ACHIEVABLE rate, not to the duration target.
// The first build asked for 64 ops when only ~4.5 fit in a frame, so every loop
// iteration overran v-blank by ~14x and the PC ticker updated once every 14
// frames. At 8 the iteration fits one or two frames and the ticker is smooth.
// It stays a runtime dial for fine trim, as does the SYNC cadence.
#define OPS_PER_FRAME 8
// Act 2's cadence, MEASURED. At one node per frame the walk is draw-bound at
// ~1.9 frames/node -- Act 2's edges are far cheaper than Act 1's, because they
// join two points in the address-space picture rather than sweeping a turtle
// across the canvas -- so 374 nodes came to ~700 frames = ~12 s, under the
// plan's 20-30 s. The payload is fixed at this phase (the CRCs must not move),
// so the dial is the cadence: advance the walk once every ACT2_FRAME_DIV frames.
// 374 x 4 = ~1,500 frames = ~25 s, and 4 > 1.9 so the divider binds rather than
// the flush.
#define ACT2_FRAME_DIV 4
#define SEAM_BEAT_FRAMES 90      // 1.5 s freeze-frame on the device seam
#define VERDICT_FRAMES 150       // verdict hold before the act loops

