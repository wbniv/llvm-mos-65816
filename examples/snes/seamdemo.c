int main(void) {
  static App a;

  // FIRST, before anything touches the screen: force-blank and zero every PPU
  // control register. bsnes-jg fills the ones a ROM never writes with
  // clock()-seeded noise, so without this the picture differs on every boot while
  // the WRAM verdict stays perfectly deterministic -- the failure mode the
  // cartsize canary spent a whole plan on (811c1f8). display_init() calls it too;
  // this call is the one guaranteed to precede everything.
  snes_ppu_reset_blank();

  app_init(&a);

  static TitleLayer title;
  title_begin16(&a.screen, &title, "SEAM DEMO", "ACT 1 - THE CARTRIDGE IS THE PROGRAM");
  uint16_t boot_st = boot_checks();
  title_end(&a.screen, &title, 110);

  seamvm_init(&a.vm);
  a.vm.status = boot_st;
  a.gr.status = 0;
  a.act = 1;
  a.tick = 0;
  a.cycle_ok = 0;
  a.at.status = 0;
  a.mode = MODE_RUN;
  a.pause = 0;
  a.laps = 0;
  a.pass = 0;
  act1_status = boot_st;
  act1_seam_hits = 0;
  act1_laps = 0;

  for (;;) {
    if (a.pause) {
      a.pause--;
      if (a.pause == 0) {
        if (a.mode == MODE_VERDICT) {
          canvas_clear(&a.canvas);
          if (a.act == 1) {
            // Hand off to Act 2 -- the plan's three-act cycle. P3 replaces the
            // wrap-around below with the hand-off to Act 3.
            a.act = 2;
            a.tick = 0;
            seamgraph_init(&a.gr);
            upq_push_cgram(&a.screen.q, 0, PAL_WEB, 0x00, (uint8_t)sizeof PAL_WEB);
          } else {
            // Act 2's verdict is up; run Act 3, then start the next cycle.
            // act3_run() takes the screen over (Mode 7 needs the VRAM the BG3
            // canvas occupies) and returns force-blanked.
            act3_run(&a);
            uint16_t h3 = seamatlas_final_crc(&a.at);
            if (h3 != SEAMDEMO_ACT3_CRC) a.at.status |= SEAMATLAS_ST_CRC;
            if (a.at.samples != SEAMDEMO_ACT3_SAMPLES) a.at.status |= SEAMATLAS_ST_PAGES;
            act3_crc = h3;
            act3_status = a.at.status;
            act3_pages = a.at.pages;

            // The full three-act fold. This is the value the plan says latches
            // after one complete cycle, and it is recomputed identically on every
            // later cycle, so it never moves once correct.
            corpus_result = seamvm_fold(
                seamvm_fold(seamvm_fold(seamvm_fold(seamvm_fold(seamvm_fold(0,
                    (uint8_t)(act1_crc & 0xFFu)), (uint8_t)(act1_crc >> 8)),
                    (uint8_t)(act2_crc & 0xFFu)), (uint8_t)(act2_crc >> 8)),
                    (uint8_t)(h3 & 0xFFu)), (uint8_t)(h3 >> 8));

            uint16_t cyc = (uint16_t)(a.vm.status | a.gr.status | a.at.status);
            if (corpus_result != SEAMDEMO_CORPUS_RESULT) cyc |= 0x8000u;
            cycle_status = cyc;
            a.cycle_ok = (uint8_t)(cyc == 0u);
            cycles = (uint16_t)(cycles + 1u);

            // Rebuild the BG3 world Act 3 overwrote. display_init() re-asserts
            // force-blank and resets the VRAM allocator, so the re-reserve is
            // legal again and the first display_frame below releases the blank.
            app_init(&a);
            a.act = 1;
            a.laps = (uint16_t)(a.laps + 1u);
            act1_laps = a.laps;
            uint16_t keep = a.vm.status;
            seamvm_init(&a.vm);
            a.vm.status = keep;
          }
        } else {
          upq_push_cgram(&a.screen.q, 0, a.cycle_ok ? PAL_RUN_OK : PAL_RUN, 0x00,
                         (uint8_t)sizeof PAL_RUN);
        }
        a.mode = MODE_RUN;
      }
    } else if (a.act == 1) {
      for (uint8_t n = OPS_PER_FRAME; n != 0; n--) {
        seamvm_step(&a.vm, &a.canvas);
        if (a.vm.seam_hit) {
          a.vm.seam_hit = 0;
          act1_seam_hits = (uint16_t)(act1_seam_hits + 1u);
          a.mode = MODE_SEAM;
          a.pause = SEAM_BEAT_FRAMES;
          upq_push_cgram(&a.screen.q, 0, PAL_SEAM, 0x00, (uint8_t)sizeof PAL_SEAM);
          break;
        }
        if (a.vm.halted) break;
        if (a.vm.ops > SEAMDEMO_ACT1_OP_BUDGET) {
          a.vm.status |= SEAMVM_ST_BUDGET;
          a.vm.halted = 1;
          break;
        }
        if (a.vm.yield) {
          a.pause = a.vm.yield;
          a.vm.yield = 0;
          break;
        }
      }
      if (a.vm.halted && a.mode != MODE_VERDICT) {
        uint16_t h = seamvm_final_crc(&a.vm);
        a.vm.crc = h;
        if (h != SEAMDEMO_ACT1_CRC) a.vm.status |= SEAMVM_ST_CRC;
        a.pass = (uint8_t)(a.vm.status == 0);
        act1_crc = h;
        act1_status = a.vm.status;
        a.mode = MODE_VERDICT;
        a.pause = VERDICT_FRAMES;
      }
    } else {
      a.tick++;
      if (a.tick >= ACT2_FRAME_DIV) {
        a.tick = 0;
        if (!a.gr.done) seamgraph_step(&a.gr, &a.canvas);
      }
      if (a.gr.done && a.mode != MODE_VERDICT) {
        uint16_t h = seamgraph_final_crc(&a.gr);
        a.gr.crc = h;
        if (h != SEAMDEMO_ACT2_CRC) a.gr.status |= SEAMGRAPH_ST_CRC;
        a.pass = (uint8_t)((a.gr.status == 0) && (a.vm.status == 0));
        act2_crc = h;
        act2_status = a.gr.status;
        act2_nodes = a.gr.visited;
        act2_seam_edges = a.gr.seam_edges;
        // P2: the corpus channel carries acts 1 and 2. P3 replaces this with the
        // full three-act fold (SEAMDEMO_CORPUS_RESULT).
        corpus_result = seamvm_fold(
            seamvm_fold(seamvm_fold(seamvm_fold(0, (uint8_t)(act1_crc & 0xFFu)),
                                    (uint8_t)(act1_crc >> 8)),
                        (uint8_t)(h & 0xFFu)),
            (uint8_t)(h >> 8));
        a.mode = MODE_VERDICT;
        a.pause = VERDICT_FRAMES;
      }
    }

#ifndef SEAMDEMO_NO_HUD
    hud_build(&a);
#endif
    act1_ops = a.vm.ops;
    demo_frames = (uint16_t)(demo_frames + 1u);
    display_frame(&a.screen);
  }
  return 0;
}

