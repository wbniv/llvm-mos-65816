// Pacing measurement (dev/seamdemo.sh step 5b): run the VM flat out and count how
// many ops fit in 60 v-blanks. The HVBJOY poll between ops is inside the measured
// cost, so the answer is a LOWER bound on the achievable ops/frame -- the safe
// direction to size OPS_PER_FRAME against.
int main(void) {
  static App a;
  static SeamVm bv;
  snes_ppu_reset_blank();
  app_init(&a);
  bv.status = boot_checks();
  seamvm_init(&bv);

  uint16_t frames = 0;
  uint8_t was = (uint8_t)(REG_HVBJOY & HVBJOY_VBLANK);
  unsigned long n = 0;
  while (frames < 60 && !bv.halted) {
    seamvm_step(&bv, &a.canvas);
    n++;
    uint8_t now = (uint8_t)(REG_HVBJOY & HVBJOY_VBLANK);
    if (now && !was) frames++;
    was = now;
  }
  bench_ops = n;
  act1_status = bv.status;
  corpus_result = (uint16_t)(n / 60u);
  act1_crc = (uint16_t)(n / 60u);
  for (;;) __asm__ volatile("wai");
  return 0;
}

