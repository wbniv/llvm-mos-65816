// seamdemo.c — Act 1 of the ExHiROM three-act boundary synthesis cartridge.
//
// "The cartridge is the program." A 16-opcode bytecode VM executes a stream that
// spans the whole 6 MiB image: one ~256-byte chapter per 32 KiB slot, JFAR-chained
// in ascending FILE order, so the VM's 24-bit program counter marches the entire
// cartridge. The centrepiece is that counter rolling file $3FFFFF -> $400000 --
// CPU $FF:FFFF -> $40:0000, the non-monotonic device seam -- where the generator
// hand-laid a SYNC instruction whose OPCODE is the last byte of physical ROM 1 and
// whose OPERAND is the first byte of physical ROM 2. One VM instruction split
// across two mask ROMs; this ROM detects it and holds a freeze-frame beat on it.
//
// Nothing here knows an address. Every opcode value, the file->CPU translation
// table, the entry point, the seam offset and the expected fold come from
// seamdemo-data.h, generated by tools/snes-seamdemo-gen.py from the authoritative
// model tools/snes_cartmap.py. The VM itself is examples/65816/seamdemo_vm.h,
// shared verbatim with the host harness tools/seamdemo-sim.c. The contract is the
// "P0 design" section of
// docs/plans/2026-08-01-exhirom-three-act-synthesis-cart.md.
//
// Codegen under test -- the heaviest sustained indirect-control-flow load any demo
// here puts on the #320/#321 backend:
//   * every opcode is a FAR fetch (indirect-long `lda [dp]`, a 24-bit cursor that
//     must not lose its bank byte across the device seam),
//   * dispatch is a dense 16-way switch, which must lower to a jump table
//     (JMP (abs,X) -- the JMPIdxIndir pseudo), and
//   * the ALU ops go through a function-pointer table (jsr __call_indir).
// dev/seamdemo.sh asserts all three in the disassembly.
//
// +mos-a16 only: a runtime far pointer is a 32-bit value and 32-bit value
// legalization exists only under +mos-a16 -- same reason as cartsize-canary.c and
// examples/65816/far_indir.c. The differential is host oracle == +mos-a16 @ bsnes-jg.
//
// Built + gated by dev/seamdemo.sh (host: dev/run.sh seamdemo).

